import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const baselinePath = path.join(root, 'deploy/magpie/upstream/api.json')
const runtime = path.resolve(process.env.MAGPIE_UPSTREAM_RUNTIME || path.join(os.homedir(), '.agents/crosery/magpie-upstream'))
const repository = 'https://github.com/yetone/magpie.git'
const label = 'com.crosery.magpie-upstream-check'
const plist = path.join(os.homedir(), 'Library/LaunchAgents', `${label}.plist`)
const json = value => `${JSON.stringify(value, null, 2)}\n`
const routeId = route => `${route.surface} ${route.method} ${route.path}`
const comparableRoute = route => ({ ...route, source: undefined, handlerHash: undefined })
const typeName = name => `Magpie_${name.replaceAll('.', '_')}`

export function compareContracts(before, after) {
  if (before.version !== 1 || after.version !== 1) throw new Error('Unsupported upstream contract version')
  const oldRoutes = new Map(before.routes.map(route => [routeId(route), route]))
  const newRoutes = new Map(after.routes.map(route => [routeId(route), route]))
  return {
    addedRoutes: [...newRoutes.keys()].filter(id => !oldRoutes.has(id)).sort(),
    removedRoutes: [...oldRoutes.keys()].filter(id => !newRoutes.has(id)).sort(),
    changedRoutes: [...newRoutes].filter(([id, route]) => oldRoutes.has(id)
      && json(comparableRoute(route)) !== json(comparableRoute(oldRoutes.get(id)))).map(([id]) => id).sort(),
    changedSchemas: [...new Set([...Object.keys(before.schemas), ...Object.keys(after.schemas)])]
      .filter(name => json(before.schemas[name]) !== json(after.schemas[name])).sort(),
    implementationFiles: [...new Set([...Object.keys(before.sourceFiles), ...Object.keys(after.sourceFiles)])]
      .filter(name => before.sourceFiles[name] !== after.sourceFiles[name]).sort(),
    addedLoginAgents: after.loginAgents.filter(id => !before.loginAgents.includes(id)).sort(),
    removedLoginAgents: before.loginAgents.filter(id => !after.loginAgents.includes(id)).sort(),
    diagnostics: after.diagnostics,
  }
}

function tsShape(schema, schemas) {
  switch (schema.kind) {
    case 'string': return 'string'
    case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'ref': return schemas[schema.ref] ? typeName(schema.ref) : 'unknown'
    case 'array': return `Array<${tsShape(schema.items, schemas)}>`
    case 'nullable': return `(${tsShape(schema.items, schemas)}) | null`
    case 'map': return `Record<string, ${tsShape(schema.items, schemas)}>`
    case 'object': return schema.fields?.length
      ? `{\n${schema.fields.map(field => `  ${JSON.stringify(field.name)}${field.optional ? '?' : ''}: ${tsShape(field.type, schemas)}`).join('\n')}\n}`
      : 'Record<string, never>'
    default: return 'unknown'
  }
}

export function generateTypes(contract) {
  const routes = contract.routes.filter(route => !route.buildConstraint)
  const declarations = Object.entries(contract.schemas).sort(([a], [b]) => a.localeCompare(b))
    .map(([name, schema]) => `export type ${typeName(name)} = ${tsShape(schema, contract.schemas)}`)
  return [
    '// Generated by scripts/magpie-upstream.mjs. Do not edit.',
    '// Source shapes only: unknown means the wire contract was not statically proved.',
    '// Upstream Magpie, Copyright (c) 2026 yetone, MIT. See deploy/magpie/upstream/LICENSE.',
    `export const MAGPIE_API_REVISION = ${JSON.stringify(contract.revision)} as const`,
    `export const MAGPIE_LOGIN_AGENTS = ${JSON.stringify(contract.loginAgents)} as const`,
    `export const MAGPIE_API_ROUTES = ${JSON.stringify(routes.map(route => ({
      id: routeId(route), surface: route.surface, method: route.method, path: route.path, actions: route.actions,
    })), null, 2)} as const`,
    'export type MagpieRouteId = typeof MAGPIE_API_ROUTES[number]["id"]',
    `export type MagpieUpstreamRequests = {\n${routes.map(route =>
      `  ${JSON.stringify(routeId(route))}: ${tsShape(route.request, contract.schemas)}`).join('\n')}\n}`,
    `export type MagpieUpstreamResponses = {\n${routes.map(route =>
      `  ${JSON.stringify(routeId(route))}: ${route.responseTypes.length
        ? route.responseTypes.map(name => contract.schemas[name] ? typeName(name) : 'unknown').join(' | ')
        : 'unknown'}`).join('\n')}\n}`,
    ...declarations,
    '',
  ].join('\n\n')
}

export function generateReference(contract) {
  const rows = contract.routes.map(route => `| ${route.surface} | \`${route.method}\` | \`${route.path.replaceAll('|', '\\|')}\` | ${route.actions.length ? route.actions.join(', ') : '-'} | \`${route.source}\` | ${route.buildConstraint ? `\`${route.buildConstraint}\`` : '-'} |`)
  return [
    '# Magpie Source API Contract', '',
    'Generated by `scripts/magpie-upstream.mjs`; do not edit.', '',
    `Source revision: \`${contract.revision}\`.`, '',
    'Upstream Magpie: Copyright (c) 2026 yetone, MIT; see `LICENSE`.', '',
    'This is a source inventory, not a claim that Crosery exposes these routes.',
    'Management routes live in the upstream GUI backend, not the inference listener.',
    'Unknown request/response shapes, custom JSON marshaling and dynamic dispatch',
    'require wire-level tests. Build-conditional routes are listed but not emitted',
    'into the default TypeScript route registry. Go GET patterns also match HEAD.', '',
    `Login agents: ${contract.loginAgents.map(id => `\`${id}\``).join(', ')}.`, '',
    '| Surface | Method | Path | Actions | Source | Build Condition |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows, '',
    'The JSON artifact retains inferred input fields, response type references,',
    'JSON tags, query parameters, handler fingerprints and package source hashes.',
    'Standard API bodies assembled dynamically remain unknown; they are not invented.',
    '',
  ].join('\n')
}

function run(command, args, options = {}) {
  try {
    return execFileSync(command, args, {
      encoding: 'utf8', timeout: 120_000, maxBuffer: 8 * 1024 * 1024,
      stdio: ['ignore', 'pipe', 'ignore'], ...options,
    })
  } catch {
    throw new Error(`${path.basename(command)} failed during upstream contract inspection`)
  }
}

function git(args, cwd) {
  return run('git', ['-c', 'core.hooksPath=/dev/null', '-c', 'core.fsmonitor=false', ...args], {
    cwd, env: { ...process.env, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null', GIT_TERMINAL_PROMPT: '0' },
  })
}

export function extractContract(source) {
  const revision = git(['rev-parse', 'HEAD'], source).trim()
  if (!/^[a-f0-9]{40}$/.test(revision) || git(['status', '--porcelain'], source).trim()) {
    throw new Error('Contract extraction requires a clean, committed source checkout')
  }
  return JSON.parse(run('go', ['run', path.join(root, 'scripts/magpie-api/main.go'), '-source', source, '-revision', revision]))
}

async function writeAtomic(filename, contents) {
  await fs.mkdir(path.dirname(filename), { recursive: true, mode: 0o700 })
  const temporary = `${filename}.${process.pid}.tmp`
  await fs.writeFile(temporary, contents, { flag: 'wx', mode: 0o600 })
  try { await fs.rename(temporary, filename) } finally { await fs.rm(temporary, { force: true }) }
}

export async function writeArtifacts(contract, directory, typesPath) {
  await writeAtomic(path.join(directory, 'api.json'), json(contract))
  await writeAtomic(path.join(directory, 'API.md'), generateReference(contract))
  await writeAtomic(typesPath, generateTypes(contract))
}

export async function publishCandidate(contract, directory) {
  const contents = json(contract)
  const expected = {
    'api.json': contents, 'API.md': generateReference(contract), 'magpie-upstream.generated.ts': generateTypes(contract),
  }
  const digest = createHash('sha256').update(json(expected)).digest('hex')
  const artifact = `${contract.revision}-${digest.slice(0, 16)}`
  await fs.mkdir(directory, { recursive: true, mode: 0o700 })
  const destination = path.join(directory, artifact)
  const existing = await fs.lstat(destination).catch(error => { if (error.code === 'ENOENT') return null; throw error })
  if (existing) {
    if (!existing.isDirectory() || existing.isSymbolicLink()) throw new Error('Invalid candidate artifacts')
    for (const [name, value] of Object.entries(expected)) {
      const filename = path.join(destination, name)
      if (!(await fs.lstat(filename)).isFile() || await fs.readFile(filename, 'utf8') !== value) {
        throw new Error('Existing candidate artifacts changed')
      }
    }
    return artifact
  }
  const staging = await fs.mkdtemp(path.join(directory, '.pending-'))
  try {
    await writeArtifacts(contract, staging, path.join(staging, 'magpie-upstream.generated.ts'))
    await fs.rename(staging, destination)
  } finally {
    await fs.rm(staging, { recursive: true, force: true })
  }
  return artifact
}

async function publicJSON(url) {
  const response = await fetch(url, {
    headers: { accept: 'application/vnd.github+json', 'user-agent': 'Crosery-Magpie-Contract-Check' },
    signal: AbortSignal.timeout(20_000), redirect: 'error',
  })
  if (!response.ok) { await response.body?.cancel(); throw new Error('GitHub upstream metadata unavailable') }
  const parts = []
  let size = 0
  for await (const chunk of response.body) {
    size += chunk.length
    if (size > 2 * 1024 * 1024) throw new Error('Upstream metadata is too large')
    parts.push(chunk)
  }
  return JSON.parse(Buffer.concat(parts).toString('utf8'))
}

async function candidateCheckout(revision) {
  if (!/^[a-f0-9]{40}$/.test(revision)) throw new Error('Invalid upstream revision')
  const source = path.join(runtime, 'source')
  await fs.mkdir(runtime, { recursive: true, mode: 0o700 })
  const stat = await fs.lstat(source).catch(error => { if (error.code === 'ENOENT') return null; throw error })
  if (stat?.isSymbolicLink() || (stat && !stat.isDirectory())) throw new Error('Invalid upstream source directory')
  if (!stat) {
    await fs.mkdir(source, { mode: 0o700 })
    git(['init'], source)
    git(['remote', 'add', 'origin', repository], source)
  }
  if (git(['remote', 'get-url', 'origin'], source).trim() !== repository) throw new Error('Unexpected upstream repository')
  if (git(['status', '--porcelain'], source).trim()) throw new Error('Refusing to change a dirty upstream checkout')
  git(['fetch', '--depth', '1', 'origin', revision], source)
  git(['checkout', '--detach', revision], source)
  return source
}

export async function withUpstreamLock(directory, action) {
  await fs.mkdir(directory, { recursive: true, mode: 0o700 })
  const filename = path.join(directory, 'check.lock')
  let lock
  try {
    lock = await fs.open(filename, 'wx', 0o600)
  } catch (error) {
    if (error.code === 'EEXIST') throw new Error('Upstream check is locked; verify the recorded process before removing a stale check.lock')
    throw error
  }
  try {
    await lock.writeFile(json({ pid: process.pid, startedAt: new Date().toISOString() }))
    return await action()
  } finally {
    await lock.close()
    await fs.rm(filename, { force: true })
  }
}

export async function checkUpstream(options = {}) {
  return withUpstreamLock(runtime, () => inspectUpstream(options))
}

async function inspectUpstream({ source } = {}) {
  const baseline = JSON.parse(await fs.readFile(baselinePath, 'utf8'))
  let previous
  try { previous = JSON.parse(await fs.readFile(path.join(runtime, 'status.json'), 'utf8')) } catch { /* First run. */ }
  let stage = 'public-metadata'
  try {
    const [commit, release, rtk] = source ? [null, null, null] : await Promise.all([
      publicJSON('https://api.github.com/repos/yetone/magpie/commits/main'),
      publicJSON('https://api.github.com/repos/yetone/magpie-releases/releases/latest').catch(() => null),
      publicJSON('https://api.github.com/repos/rtk-ai/rtk/releases/latest').catch(() => null),
    ])
    stage = 'source-checkout'
    const checkout = source || await candidateCheckout(commit.sha)
    stage = 'source-extraction'
    const candidate = extractContract(checkout)
    const diff = compareContracts(baseline, candidate)
    const changed = baseline.revision !== candidate.revision
    stage = 'candidate-publication'
    const artifact = await publishCandidate(candidate, path.join(runtime, 'candidates'))
    const status = {
      version: 1, checkedAt: new Date().toISOString(), status: changed ? 'review_required' : 'unchanged',
      baselineRevision: baseline.revision, candidateRevision: candidate.revision,
      latestRelease: release?.tag_name || null, rtkRelease: rtk?.tag_name || null,
      diff, artifact: `candidates/${artifact}`,
      note: 'Candidate contracts and types are generated automatically; running code and credentials are not changed.',
    }
    stage = 'status-publication'
    await writeAtomic(path.join(runtime, 'status.json'), json(status))
    return status
  } catch {
    const status = { version: 1, ...previous, checkedAt: new Date().toISOString(), status: 'error', errorStage: stage,
      error: `Upstream check failed at ${stage}; the previous candidate and running kernel were retained.` }
    await writeAtomic(path.join(runtime, 'status.json'), json(status))
    throw new Error(status.error)
  }
}

export function checkServiceEnvironment(env = process.env) {
  const result = { MAGPIE_UPSTREAM_RUNTIME: runtime, PATH: env.PATH || '/usr/bin:/bin:/usr/sbin:/sbin' }
  for (const name of ['HTTPS_PROXY', 'HTTP_PROXY', 'ALL_PROXY', 'https_proxy', 'http_proxy', 'all_proxy']) {
    if (!env[name]) continue
    const url = new URL(env[name])
    if (!['http:', 'https:', 'socks5:', 'socks5h:'].includes(url.protocol) || url.username || url.password ||
        url.search || url.hash || (url.pathname && url.pathname !== '/')) {
      throw new Error('Scheduled checks require credential-free proxy settings')
    }
    result[name] = url.href
  }
  for (const name of ['NO_PROXY', 'no_proxy']) {
    if (!env[name]) continue
    if (env[name].length > 4096 || ['\r', '\n', '\0'].some(character => env[name].includes(character))) throw new Error('Invalid proxy exclusion setting')
    result[name] = env[name]
  }
  return result
}

async function installCheck() {
  if (process.platform !== 'darwin') throw new Error('The scheduled local check uses macOS LaunchAgent')
  const environment = checkServiceEnvironment()
  let existing = false
  try { await fs.access(plist); existing = true } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
  if (existing) {
    if (!process.argv.includes('--replace')) throw new Error('Upstream check service already exists')
    const current = JSON.parse(run('plutil', ['-convert', 'json', '-o', '-', plist]))
    if (current.Label !== label || current.ProgramArguments?.[1] !== path.join(root, 'scripts/magpie-upstream.mjs')) {
      throw new Error('Refusing to replace an unrelated check service')
    }
    run('launchctl', ['bootout', `gui/${process.getuid()}`, plist])
  }
  const xml = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')
  const args = [process.execPath, path.join(root, 'scripts/magpie-upstream.mjs'), 'check']
  await fs.mkdir(runtime, { recursive: true, mode: 0o700 })
  await fs.mkdir(path.dirname(plist), { recursive: true })
  await writeAtomic(plist, `<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0"><dict>
<key>Label</key><string>${label}</string>
<key>ProgramArguments</key><array>${args.map(arg => `<string>${xml(arg)}</string>`).join('')}</array>
<key>WorkingDirectory</key><string>${xml(root)}</string>
<key>EnvironmentVariables</key><dict>${Object.entries(environment).map(([key, value]) => `<key>${xml(key)}</key><string>${xml(value)}</string>`).join('')}</dict>
<key>RunAtLoad</key><true/><key>StartInterval</key><integer>1800</integer>
<key>StandardOutPath</key><string>${xml(path.join(runtime, 'check.log'))}</string>
<key>StandardErrorPath</key><string>${xml(path.join(runtime, 'check-errors.log'))}</string>
</dict></plist>\n`)
  run('launchctl', ['bootstrap', `gui/${process.getuid()}`, plist])
  console.log(json({ installed: label, intervalSeconds: 1800, mode: 'detect-and-generate-only' }))
}

async function main() {
  const action = process.argv[2]
  const arg = name => { const position = process.argv.indexOf(name); return position < 0 ? undefined : process.argv[position + 1] }
  if (action === 'generate' || action === 'verify') {
    const source = arg('--source') || process.env.MAGPIE_SOURCE
    if (!source) throw new Error('Pass --source with a clean upstream checkout')
    const contract = extractContract(path.resolve(source))
    const directory = path.dirname(baselinePath)
    const typesPath = path.join(root, 'packages/contracts/magpie-upstream.generated.ts')
    if (action === 'generate') await writeArtifacts(contract, directory, typesPath)
    else {
      const outputs = [[baselinePath, json(contract)], [path.join(directory, 'API.md'), generateReference(contract)], [typesPath, generateTypes(contract)]]
      for (const [filename, expected] of outputs) {
        if (await fs.readFile(filename, 'utf8') !== expected) throw new Error('Generated upstream artifacts are stale')
      }
    }
    console.log(json({ action, revision: contract.revision, routes: contract.routes.length, schemas: Object.keys(contract.schemas).length, loginAgents: contract.loginAgents, diagnostics: contract.diagnostics }))
  } else if (action === 'check') {
    const result = await checkUpstream({ source: arg('--source') })
    console.log(json({ status: result.status, revision: result.candidateRevision, artifact: result.artifact, diff: result.diff }))
  } else if (action === 'install-check') await installCheck()
  else throw new Error('Use generate, verify, check, or install-check')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1 })
}

export function compareContracts(before, after) {
  if (before.version !== 1 || after.version !== 1) throw new Error('Unsupported upstream contract version')
  const oldRoutes = new Map(before.routes.map(route => [routeId(route), route]))
  const newRoutes = new Map(after.routes.map(route => [routeId(route), route]))
  return {
    addedRoutes: [...newRoutes.keys()].filter(id => !oldRoutes.has(id)).sort(),
    removedRoutes: [...oldRoutes.keys()].filter(id => !newRoutes.has(id)).sort(),
    changedRoutes: [...newRoutes].filter(([id, route]) => oldRoutes.has(id)
      && json(comparableRoute(route)) !== json(comparableRoute(oldRoutes.get(id)))).map(([id]) => id).sort(),
    changedSchemas: [...new Set([...Object.keys(before.schemas), ...Object.keys(after.schemas)])]
      .filter(name => json(before.schemas[name]) !== json(after.schemas[name])).sort(),
    implementationFiles: [...new Set([...Object.keys(before.sourceFiles), ...Object.keys(after.sourceFiles)])]
      .filter(name => before.sourceFiles[name] !== after.sourceFiles[name]).sort(),
    addedLoginAgents: after.loginAgents.filter(id => !before.loginAgents.includes(id)).sort(),
    removedLoginAgents: before.loginAgents.filter(id => !after.loginAgents.includes(id)).sort(),
    diagnostics: after.diagnostics,
  }
}

function tsShape(schema, schemas) {
  switch (schema.kind) {
    case 'string': return 'string'
    case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'ref': return schemas[schema.ref] ? typeName(schema.ref) : 'unknown'
    case 'array': return `Array<${tsShape(schema.items, schemas)}>`
    case 'nullable': return `(${tsShape(schema.items, schemas)}) | null`
    case 'map': return `Record<string, ${tsShape(schema.items, schemas)}>`
    case 'object': return schema.fields?.length
      ? `{\n${schema.fields.map(field => `  ${JSON.stringify(field.name)}${field.optional ? '?' : ''}: ${tsShape(field.type, schemas)}`).join('\n')}\n}`
      : 'Record<string, never>'
    default: return 'unknown'
  }
}

export function generateTypes(contract) {
  const routes = contract.routes.filter(route => !route.buildConstraint)
  const declarations = Object.entries(contract.schemas).sort(([a], [b]) => a.localeCompare(b))
    .map(([name, schema]) => `export type ${typeName(name)} = ${tsShape(schema, contract.schemas)}`)
  return [
    '// Generated by scripts/magpie-upstream.mjs. Do not edit.',
    '// Source shapes only: unknown means the wire contract was not statically proved.',
    '// Upstream Magpie, Copyright (c) 2026 yetone, MIT. See deploy/magpie/upstream/LICENSE.',
    `export const MAGPIE_API_REVISION = ${JSON.stringify(contract.revision)} as const`,
    `export const MAGPIE_LOGIN_AGENTS = ${JSON.stringify(contract.loginAgents)} as const`,
    `export const MAGPIE_API_ROUTES = ${JSON.stringify(routes.map(route => ({
      id: routeId(route), surface: route.surface, method: route.method, path: route.path, actions: route.actions,
    })), null, 2)} as const`,
    'export type MagpieRouteId = typeof MAGPIE_API_ROUTES[number]["id"]',
    `export type MagpieUpstreamRequests = {\n${routes.map(route =>
      `  ${JSON.stringify(routeId(route))}: ${tsShape(route.request, contract.schemas)}`).join('\n')}\n}`,
    `export type MagpieUpstreamResponses = {\n${routes.map(route =>
      `  ${JSON.stringify(routeId(route))}: ${route.responseTypes.length
        ? route.responseTypes.map(name => contract.schemas[name] ? typeName(name) : 'unknown').join(' | ')
        : 'unknown'}`).join('\n')}\n}`,
    ...declarations,
    '',
  ].join('\n\n')
}

